"""Read-only, exact round-trip audit of a DX2Ed source-private Box OBJ.

This accepts an editor-authored Box specification (or named private draft copy)
and the *unchanged* Wavefront OBJ generated by private_brush_obj. It performs
a separate bounded OBJ topology check, then requires byte-for-byte canonical
equality with a fresh independently preflighted export.

It is NOT an arbitrary OBJ importer, DX2 BSP/CSG compiler, collision cooker,
original actor exporter or retail-game validator. No output files are written.
"""
from __future__ import annotations

import argparse
from collections import defaultdict
import hashlib
import json
import math
from pathlib import Path
import re
import stat
import sys
from typing import Any

from .private_brush_obj import MAX_OBJ_BYTES, _load_private_json, render_private_box_obj
from .private_brush_preflight import inspect_private_box_convex, inspect_private_draft_copy

SCHEMA = "DX2SDK-private-Box-OBJ-roundtrip-audit-v1"
_FACE_REF = re.compile(r"([1-9][0-9]*)//([1-9][0-9]*)")
_GROUP = re.compile(r"private_(?:box_side|cut_cap)_[0-9]{2}")


def _vector(items: list[str]) -> tuple[float, float, float]:
    if len(items) != 3:
        raise ValueError("OBJ vector must have exactly three coordinates")
    try:
        coordinates = tuple(float(value) for value in items)
    except ValueError as exc:
        raise ValueError("OBJ coordinate is not numeric") from exc
    if not all(math.isfinite(value) for value in coordinates):
        raise ValueError("OBJ coordinates must be finite")
    return coordinates


def _cross(a, b):
    return (a[1]*b[2] - a[2]*b[1],
            a[2]*b[0] - a[0]*b[2],
            a[0]*b[1] - a[1]*b[0])


def _sub(a, b):
    return tuple(x-y for x, y in zip(a, b))


def _dot(a, b):
    return sum(x*y for x, y in zip(a, b))


def _inspect_obj(payload: bytes) -> dict:
    """Check a strict, private-only triangulated OBJ without using the exporter."""
    if type(payload) is not bytes or not 0 < len(payload) <= MAX_OBJ_BYTES:
        raise ValueError("Only bounded private OBJ bytes <=128 KiB are accepted")
    try:
        lines = payload.decode("ascii").splitlines()
    except UnicodeError as exc:
        raise ValueError("Only ASCII private Wavefront OBJ is accepted") from exc
    vertices: list[tuple[float, float, float]] = []
    normals: list[tuple[float, float, float]] = []
    triangles: list[tuple[tuple[int, int, int], int]] = []
    group_names: set[str] = set()
    group_uses: dict[str, int] = defaultdict(int)
    current_group: str | None = None
    seen_object = False
    seen_smoothing = False
    for line in lines:
        if not line:
            raise ValueError("Blank OBJ lines are not part of the private format")
        if line.startswith("#"):
            continue
        parts = line.split()
        if not parts:
            raise ValueError("Malformed OBJ line")
        command, arguments = parts[0], parts[1:]
        if command == "o":
            if seen_object or arguments != ["DX2Ed_Private_Box"]:
                raise ValueError("Unexpected OBJ object declaration")
            seen_object = True
        elif command == "s":
            if seen_smoothing or arguments != ["off"]:
                raise ValueError("Unexpected OBJ smoothing declaration")
            seen_smoothing = True
        elif command == "v":
            if current_group is not None or len(vertices) >= 64:
                raise ValueError("Late or excess private OBJ vertex")
            vertices.append(_vector(arguments))
        elif command == "vn":
            if current_group is not None or len(normals) >= 14:
                raise ValueError("Late or excess private OBJ normal")
            normal = _vector(arguments)
            if not math.isclose(_dot(normal, normal), 1.0, abs_tol=0.0001):
                raise ValueError("Non-unit private OBJ normal")
            normals.append(normal)
        elif command == "g":
            if (len(arguments) != 1 or not _GROUP.fullmatch(arguments[0])
                    or arguments[0] in group_names or len(group_names) >= 14
                    or not vertices or not normals):
                raise ValueError("Unexpected or repeated source-private OBJ group")
            current_group = arguments[0]
            group_names.add(current_group)
        elif command == "f":
            if current_group is None or len(arguments) != 3 or len(triangles) >= 44:
                raise ValueError("Private OBJ accepts only bounded grouped triangles")
            refs = []
            for token in arguments:
                match = _FACE_REF.fullmatch(token)
                if match is None:
                    raise ValueError("OBJ face must use positive v//vn indices")
                vi, ni = int(match.group(1)), int(match.group(2))
                if not (1 <= vi <= len(vertices) and 1 <= ni <= len(normals)):
                    raise ValueError("OBJ face index exceeds declared geometry")
                refs.append((vi - 1, ni - 1))
            indices = tuple(ref[0] for ref in refs)
            if (len(set(indices)) != 3
                    or len(set(ref[1] for ref in refs)) != 1):
                raise ValueError("Degenerate triangle or mixed per-face normals")
            a, b, c = (vertices[i] for i in indices)
            cross = _cross(_sub(b, a), _sub(c, a))
            if _dot(cross, normals[refs[0][1]]) <= 1e-10:
                raise ValueError("Degenerate or inward private OBJ triangle")
            triangles.append((indices, refs[0][1]))
            group_uses[current_group] += 1
        else:
            raise ValueError("Unsupported OBJ directive: " + command)
    if (not seen_object or not seen_smoothing
            or not 4 <= len(vertices) <= 64
            or not 4 <= len(normals) <= 14
            or not 4 <= len(triangles) <= 44
            or len(group_names) != len(normals)
            or any(group_uses[name] < 1 for name in group_names)):
        raise ValueError("Incomplete private OBJ topology")
    edge_ledger: dict[tuple[int, int], list[tuple[int, int]]] = defaultdict(list)
    signed_volume = 0.0
    used_vertices: set[int] = set()
    used_normals: set[int] = set()
    for indices, ni in triangles:
        a, b, c = indices
        used_vertices.update(indices)
        used_normals.add(ni)
        signed_volume += _dot(vertices[a],
                              _cross(vertices[b], vertices[c])) / 6.0
        for u, v in ((a, b), (b, c), (c, a)):
            edge_ledger[tuple(sorted((u, v)))].append((u, v))
    if (len(used_vertices) != len(vertices)
            or len(used_normals) != len(normals)
            or any(len(pairs) != 2 or pairs[0] != pairs[1][::-1]
                   for pairs in edge_ledger.values())
            or not math.isfinite(signed_volume) or signed_volume <= 0.0):
        raise ValueError("Private OBJ is not a closed consistently wound solid")
    return {
        "vertex_count": len(vertices), "face_count": len(group_names),
        "triangle_count": len(triangles), "triangle_edge_count": len(edge_ledger),
        "signed_volume_m3": signed_volume,
    }


def audit_private_box_obj(raw: Any, obj_data: bytes,
                          *, copy_name: str | None = None) -> dict:
    """Read-only check: validate triangles, then match exact canonical export."""
    parsed = _inspect_obj(obj_data)
    reference = (inspect_private_box_convex(raw) if copy_name is None
                 else inspect_private_draft_copy(raw, copy_name))
    canonical, expected = render_private_box_obj(raw, copy_name=copy_name)
    if any(parsed[field] != expected[field]
           for field in ("vertex_count", "face_count", "triangle_count")):
        raise ValueError("Private OBJ geometry count differs from authored Box")
    if not math.isclose(parsed["signed_volume_m3"],
                        reference["enclosed_private_volume_m3"],
                        rel_tol=1e-6, abs_tol=2e-6):
        raise ValueError("Private OBJ enclosed volume differs from authored Box")
    if obj_data != canonical:
        raise ValueError("OBJ differs from exact source-private canonical export")
    return {
        "schema": SCHEMA,
        "status": "exact-source-private-OBJ-roundtrip-verified",
        "obj_sha256": hashlib.sha256(obj_data).hexdigest(),
        "private_geometry_sha256": expected["private_geometry_sha256"],
        "source_private_spec_sha256": expected["source_private_spec_sha256"],
        **parsed,
        "exact_export_match": True,
        "original_game_files_modified": False,
        "native_world_model_writer_enabled": False,
        "native_collision_generated": False,
        "retail_game_runtime_verified": False,
    }


def audit_private_box_obj_file(source_json: Path, obj_path: Path,
                               *, copy_name: str | None = None) -> dict:
    """Accept only regular .json and .obj; never open native map resources."""
    if not isinstance(source_json, Path) or not isinstance(obj_path, Path):
        raise ValueError("Expected explicit private JSON and OBJ paths")
    if obj_path.suffix.lower() != ".obj" or obj_path.is_symlink():
        raise ValueError("Only regular private .obj files are accepted")
    try:
        metadata = obj_path.lstat()
    except OSError as exc:
        raise ValueError("Private OBJ is missing or unreadable") from exc
    if not stat.S_ISREG(metadata.st_mode) or not 0 < metadata.st_size <= MAX_OBJ_BYTES:
        raise ValueError("Only regular private OBJ files <=128 KiB are accepted")
    raw = _load_private_json(source_json)
    if (copy_name is None and type(raw) is dict
            and raw.get("schema") == "DX2Ed-prop-draft-v1"):
        raise ValueError("Select exactly one private --copy DraftProp_N")
    content = obj_path.read_bytes()
    if not 0 < len(content) <= MAX_OBJ_BYTES:
        raise ValueError("Private OBJ changed or is oversized")
    return audit_private_box_obj(raw, content, copy_name=copy_name)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Read-only exact provenance and topology audit for private Box OBJ")
    parser.add_argument("private_json", type=Path)
    parser.add_argument("output_obj", type=Path)
    parser.add_argument("--copy", dest="copy_name",
                        help="Select one original editor-private DraftProp_N")
    args = parser.parse_args(argv)
    try:
        result = audit_private_box_obj_file(
            args.private_json, args.output_obj, copy_name=args.copy_name)
        print(json.dumps(result, sort_keys=True, allow_nan=False))
        return 0
    except (OSError, ValueError, TypeError, KeyError, UnicodeError) as exc:
        print("Private OBJ round-trip audit REFUSED: " + str(exc),
              file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
