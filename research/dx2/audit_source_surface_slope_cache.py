#!/usr/bin/env python3
"""Read-only source collision-cache slope histogram, no retail mesh output.

Consumes DX2Ed's existing original-GMP-SHA-bound, source-validated cache-v2
JSON generated by the original collision picker backend. Requires the caller
to supply the expected source GMP SHA-256; does NOT independently re-decode a
retail GMP or claim runtime Havok walkability. No coordinates or triangle IDs
are emitted in results. The cache itself is PRIVATE and must not be committed.
"""
from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import json
import math
from pathlib import Path
import sys

SCHEMA = "DX2SDK-source-Level-slope-histogram-from-private-cache-v1"
CACHE_SCHEMA = "DX2Ed-source-MOPP-collision-selection-cache-v3"
EDGE_SCHEMA = "DX2Ed-MOPP-source-exact-edge-provenance-v1"
COORD = "Godot preview (Level.x/10, Level.z/10, Level.y/10)"
MAX_CACHE_BYTES = 40_000_000
MAX_FACES = 300_000
BUCKETS = (5.0, 30.0, 45.0, 75.0, 90.0000001)
BUCKET_NAMES = (
    "plane_slope_0_to_5_degrees",
    "plane_slope_over_5_to_30_degrees",
    "plane_slope_over_30_to_45_degrees",
    "plane_slope_over_45_to_75_degrees",
    "plane_slope_over_75_to_90_degrees",
)


def _whole(number, least=0, most=MAX_FACES*3):
    return type(number) is int and least <= number <= most


def _xyz(raw):
    if (not isinstance(raw, list) or len(raw) != 3
            or any(type(x) not in (int, float) or not math.isfinite(x)
                   or abs(x) > 100_000.0 for x in raw)):
        raise ValueError("Invalid private source collision XYZ")
    return tuple(float(x) for x in raw)


def _sha(value):
    return (type(value) is str and len(value) == 64
            and all(c in "0123456789abcdef" for c in value))


def inspect_document(doc: dict, expected_sha256: str):
    """Source-cache revalidation and aggregates only; never returns geometry."""
    if not isinstance(doc, dict) or not _sha(expected_sha256):
        raise ValueError("Expected original GMP SHA-256 required")
    if (doc.get("schema") != CACHE_SCHEMA
            or doc.get("source_sha256") != expected_sha256
            or doc.get("read_only") is not True
            or doc.get("not_a_native_collision_writer") is not True
            or doc.get("physics_materials_verified") is not False
            or doc.get("coordinate_system") != COORD
            or doc.get("edge_provenance_schema") != EDGE_SCHEMA
            or doc.get("source_edge_welding") != "exact_original_Level_XYZ_no_epsilon"
            or not isinstance(doc.get("source_map"), str)
            or not doc["source_map"].lower().endswith(".gmp")
            or Path(doc["source_map"]).name != doc["source_map"]):
        raise ValueError("Stale or unverified original source cache")
    vertices = doc.get("vertices_godot_xyz")
    faces = doc.get("leaf_triangles")
    if (not isinstance(vertices, list) or not isinstance(faces, list)
            or not _whole(doc.get("source_flat_vertex_count"), 3, MAX_FACES)
            or not _whole(doc.get("source_triangle_count"), 1, MAX_FACES)
            or not _whole(doc.get("mopp_leaf_triangle_count"), 1, MAX_FACES)
            or len(vertices) != doc["source_flat_vertex_count"]
            or len(faces) != doc["mopp_leaf_triangle_count"]
            or len(faces) > doc["source_triangle_count"]):
        raise ValueError("Original cache geometry counts are inconsistent")
    topo = doc.get("source_topology_summary")
    if not isinstance(topo, dict):
        raise ValueError("Missing independently audited edge topology")
    names = (
        "open_boundary_edges",
        "two_triangle_same_material_edges",
        "two_triangle_render_material_seams",
        "three_or_more_triangle_edges",
        "unique_source_edges",
    )
    if any(not _whole(topo.get(name)) for name in names):
        raise ValueError("Malformed source edge provenance summary")
    if (topo["unique_source_edges"] !=
            sum(topo[name] for name in names[:4])):
        raise ValueError("Source edge provenance totals inconsistent")
    if not _whole(topo.get("source_exact_welded_vertex_count"), 3, len(vertices)):
        raise ValueError("Missing exact source welded vertex count")
    coords = [_xyz(value) for value in vertices]
    result = Counter()
    edges = Counter()
    last_id = -1
    for face in faces:
        if not isinstance(face, dict):
            raise ValueError("Invalid original Level source face")
        tid = face.get("triangle_id")
        ids = face.get("vertex_indices")
        kinds = face.get("source_edge_kinds")
        weld = face.get("source_weld_ids")
        if (not _whole(tid, 0, doc["source_triangle_count"]-1)
                or tid <= last_id
                or not isinstance(ids, list) or len(ids) != 3
                or any(not _whole(i, 0, len(coords)-1) for i in ids)
                or not isinstance(kinds, list) or len(kinds) != 3
                or any(not _whole(k, 0, 3) for k in kinds)
                or not isinstance(weld, list) or len(weld) != 3
                or any(not _whole(w, 0, topo["source_exact_welded_vertex_count"]-1) for w in weld)
                or len(set(weld)) != 3):
            raise ValueError("Malformed original source triangle ID/index/edge class")
        last_id = tid
        a,b,c = [coords[i] for i in ids]
        ab = tuple(b[k]-a[k] for k in range(3))
        ac = tuple(c[k]-a[k] for k in range(3))
        nx = ab[1]*ac[2]-ab[2]*ac[1]
        ny = ab[2]*ac[0]-ab[0]*ac[2]
        nz = ab[0]*ac[1]-ab[1]*ac[0]
        norm = math.hypot(nx,ny,nz)
        if not math.isfinite(norm) or norm == 0:
            raise ValueError("Zero-area original collision leaf triangle")
        slope = math.degrees(math.acos(min(1.0, max(0.0,abs(ny)/norm))))
        idx = next(i for i, cap in enumerate(BUCKETS) if slope <= cap)
        result[BUCKET_NAMES[idx]] += 1
        result["original_source_leaf_triangles"] += 1
        if ny > 0:result["positive_preview_up_winding"] += 1
        elif ny < 0:result["negative_preview_up_winding"] += 1
        else:result["sideways_preview_winding"] += 1
        for kind in kinds:
            edges[kind] += 1
    if (edges[1] != topo["open_boundary_edges"]
            or edges[0] != topo["two_triangle_same_material_edges"]*2
            or edges[2] != topo["two_triangle_render_material_seams"]*2
            or edges[3] < topo["three_or_more_triangle_edges"]*3):
        raise ValueError("Original source edge incidence codes contradict topology")
    if sum(result[bn] for bn in BUCKET_NAMES) != len(faces):
        raise ValueError("Original source slope histogram incomplete")
    return {
        "schema": SCHEMA,
        "original_map_filename": doc["source_map"],
        "expected_original_gmp_sha256": expected_sha256,
        "source_triangle_total": doc["source_triangle_count"],
        "source_mopp_nonzero_area_leaf_triangles": len(faces),
        "slope_bucket_upper_degrees": [5, 30, 45, 75, 90],
        "counts": dict(result),
        "edge_uses_by_source_class": {
            "same_render_material_interior": edges[0],
            "open_boundary": edges[1],
            "different_render_material_seam": edges[2],
            "nonmanifold": edges[3],
        },
        "original_source_coordinates_in_result": False,
        "walkable_floor_or_ceiling_verified": False,
        "physics_materials_verified": False,
        "havok_runtime_compared": False,
        "native_game_bytes_modified": False,
    }


def main(argv=None):
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--cache",type=Path,required=True)
    p.add_argument("--expected-sha256",required=True,
                   help="SHA256 of the original owner GMP (not of the cache JSON)")
    p.add_argument("--report",type=Path,
                   help="Optional NEW JSON outside the source cache directory")
    args=p.parse_args(argv)
    try:
        source=args.cache.resolve()
        if not source.is_file() or not 0<source.stat().st_size<=MAX_CACHE_BYTES:
            raise ValueError("Expected bounded, private original collision cache")
        doc=json.loads(source.read_text(encoding="utf-8"))
        report=inspect_document(doc,args.expected_sha256)
        if args.report:
            dest=args.report.resolve()
            if (dest.suffix.lower()!=".json" or dest.exists()
                    or dest==source or dest.is_relative_to(source.parent)):
                raise ValueError("Report must be a new JSON outside private source cache folder")
            dest.parent.mkdir(parents=True,exist_ok=True)
            with dest.open("x",encoding="utf-8") as handle:
                json.dump(report,handle,indent=2,allow_nan=False)
                handle.write("\n")
        print(json.dumps(report,indent=2,allow_nan=False))
        return 0
    except (OSError,ValueError,TypeError,KeyError,IndexError,OverflowError,
            json.JSONDecodeError) as e:
        print(json.dumps({"status":"refused","reason":str(e)}),file=sys.stderr)
        return 1


if __name__=="__main__":
    raise SystemExit(main())
